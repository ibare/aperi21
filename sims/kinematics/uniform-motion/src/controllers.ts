// 조작기는 하나다.
//
// 자동 진행만으로 주장은 이미 끝난다 — 1초마다 자국이 찍히고 막대가 쌓여 오른쪽
// 끝이 맞는다. 이 슬라이더는 그와 별개로 다른 것을 판정한다: 간격이 같은 것이
// **이 속도의 우연이 아니라는 것.** 느리게 하면 간격이 좁아지고 빠르게 하면
// 넓어지지만, 어느 쪽이든 자기들끼리는 여전히 같다. 이건 독자가 직접 손으로 해
// 봐야 믿는 종류의 사실이라 조작기로 둔다.
//
// 잡는 순간 러너가 `heldPath` 에 true 를 적고, 그때 랩이 처음으로 돌아간다.
// 무엇을 되돌릴지는 조각이 정한다 — 여기서는 랩 전체다 (physics.step).
//
// 자리를 오른쪽 아래로 준다. 기본 자리(오른쪽 위)는 물체가 지나가는 층을 덮고,
// 왼쪽 아래는 쌓인 막대와 캡션의 자리다. 자리는 저작 결정이다 (원칙 7 ③).
// ========================================================================

import type { ControllerSpec } from '@aperi21/schema';
import { SPEED_MAX, SPEED_MIN, text } from './schema';

export const controllers: readonly ControllerSpec[] = [
  {
    id: 'speed',
    type: 'slider',
    binds: { value: 'speed' },
    heldPath: 'held',
    range: [SPEED_MIN, SPEED_MAX],
    label: text('control.speed'),
    at: { screen: 'bottom-right' },
  },
];
