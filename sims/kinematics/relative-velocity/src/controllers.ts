import type { ControllerSpec } from '@aperi21/schema';
import { U_RANGE, text } from './schema';

/**
 * 조작기는 하나다 — 어느 기준틀에서 볼지.
 *
 * **기준틀은 연속량이어야 한다.** "강둑 / 강물" 두 버튼이었다면 컷이 바뀔 뿐
 * 아무것도 기울지 않는다. 강물보다 느리게 떠가는 중간 기준틀은 전부 진짜
 * 관성계이므로 그 사이를 훑는 것은 눈속임이 아니라 **기준틀의 한 가족을 차례로
 * 들르는 것**이다.
 *
 * 범위를 1.2 **너머**까지 잡은 것도 같은 이유다. 넘기는 순간 길이 반대쪽으로
 * 기운다 — 자동 순회만으로는 절대 보여 줄 수 없는 것이고, "길이 똑바로 서는
 * 기준틀이 딱 하나뿐" 이라는 것은 직접 찾아봐야 확신이 선다.
 *
 * `heldPath` 가 인계 규약이다. 자동 순회 중에는 `step` 이 지금 값을 `ui.u` 에
 * 적어 슬라이더가 화면과 어긋나지 않고, 잡는 순간 러너가 `ui.held` 를 적으면
 * 조각이 값을 넘겨받는다. 놓은 뒤 무엇으로 돌아갈지는 조각이 안다 — 여기서는
 * 4 초 머물다 **놓은 자리에서** 순회를 이어 간다 (physics.ts).
 *
 * 자리를 선언해 둔다. 그림이 캔버스를 가로로 다 쓰므로 비어 있는 곳이 오른쪽
 * 아래(이쪽 둑과 캡션 사이)뿐이고, 자리를 선언한 조작기는 카메라가 프레이밍을
 * 비우지 않아 그림이 밀리지 않는다.
 */
export const controllers: readonly ControllerSpec[] = [
  {
    id: 'observer-speed',
    type: 'slider',
    binds: { value: 'ui.u' },
    heldPath: 'ui.held',
    range: [U_RANGE[0], U_RANGE[1]],
    label: text('label.observer'),
    // 단위 표기라 번역 대상이 아니다 (C1 판정 3).
    unit: 'm/s',
    at: { screen: 'bottom-right' },
    size: [300, 44],
  },
];
